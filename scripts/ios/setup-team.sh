#!/usr/bin/env bash
# Inject teamID from iosApp/team.properties into:
#   - iosApp/Config/Team.xcconfig (gitignored; `DEVELOPMENT_TEAM = <id>`),
#     and make Debug.xcconfig + Release.xcconfig `#include? "Team.xcconfig"`
#     (the line is added once; re-runs leave it alone).
#
# Nothing tracked is edited: the committed ExportOptions.plist keeps its
# REPLACE_WITH_TEAM_ID placeholder and export-ipa.sh writes the team into
# the temporary copy it exports with. So a release tree stays clean, and no
# one developer's team id lands in the repo.
#
# Why an xcconfig and not the project: open-frame wrote DEVELOPMENT_TEAM
# into its pbxproj. Here the .xcodeproj is generated by XcodeGen and not
# committed, so an edit there is lost on the next `xcodegen generate`; and
# putting the id in project.yml would commit one developer's team for
# everyone who builds from source. A gitignored xcconfig is per-machine,
# survives regeneration, and `#include?` (with the ?) means a clone without
# it still builds for the simulator.
#
# Idempotent: running twice produces the same files. Run once after
# Apple Developer enrollment lands, plus any time the team ID changes
# (e.g. moving from a personal team to the developer-program team).

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=common.sh
. "$SCRIPT_DIR/common.sh"

[ $# -eq 0 ] || die "setup-team.sh takes no arguments (it reads iosApp/team.properties)"

load_team_properties
require_vars IOS_TEAM_ID

# A team id is 10 upper-case alphanumerics. Checking the shape catches the
# example's REPLACE_WITH_TEAM_ID (and a pasted team NAME) before it is
# written anywhere.
if ! [[ "$IOS_TEAM_ID" =~ ^[A-Z0-9]{10}$ ]]; then
  die "teamID '$IOS_TEAM_ID' is not a 10-character Apple team id (developer.apple.com/account → Membership)"
fi

for cfg in Debug Release; do
  [ -f "$CONFIG_DIR/$cfg.xcconfig" ] || die "$CONFIG_DIR/$cfg.xcconfig not found"
done

echo "==> Writing DEVELOPMENT_TEAM=$IOS_TEAM_ID to $TEAM_XCCONFIG" >&2
cat > "$TEAM_XCCONFIG" <<EOF
// Written by scripts/ios/setup-team.sh from iosApp/team.properties.
// Gitignored: the signing team is per-machine, not part of the source.
DEVELOPMENT_TEAM = $IOS_TEAM_ID
EOF

# Include it from both configurations. Appended at the end so it wins over
# anything earlier in the file (xcconfig: last assignment wins); `#include?`
# rather than `#include` so a machine with no Team.xcconfig still builds.
for cfg in Debug Release; do
  file="$CONFIG_DIR/$cfg.xcconfig"
  if grep -qE '^[[:space:]]*#include\?[[:space:]]+"Team\.xcconfig"' "$file"; then
    echo "    $cfg.xcconfig: already includes Team.xcconfig" >&2
  else
    # Ensure the file ends in a newline before appending, so the include
    # can't be glued onto the last line.
    if [ -n "$(tail -c1 "$file")" ]; then echo >> "$file"; fi
    printf '%s\n' '// Signing team, per machine: scripts/ios/setup-team.sh writes it.' '#include? "Team.xcconfig"' >> "$file"
    echo "    $cfg.xcconfig: added #include? \"Team.xcconfig\"" >&2
  fi
done

# project.yml must not set DEVELOPMENT_TEAM: its settings override the
# xcconfig, so even an empty value there would blank the team set above.
if grep -qE '^[[:space:]]*DEVELOPMENT_TEAM[[:space:]]*:' "$PROJECT_YML"; then
  echo "warn: iosApp/project.yml still sets DEVELOPMENT_TEAM — delete that line, or it overrides Team.xcconfig" >&2
fi

echo "==> Done. Verify with:" >&2
echo "    cat $TEAM_XCCONFIG" >&2
